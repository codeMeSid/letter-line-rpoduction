/**
 * Single-stroke ("Hershey-like") glyph set. Every glyph is a list of open strokes; each stroke is a
 * polyline of [u, v] points in a unit cell: u 0..GLYPH_W (width), v 0..1 (height, v points DOWN).
 *
 * Metrics (shared by all glyphs):
 *   v 0.00  ascender / cap / digit top
 *   v 0.25  x-height line   (x-height = 0.55)
 *   v 0.80  baseline
 *   v 1.00  descender bottom
 * Glyphs are centred horizontally on u = 0.35, so a lone glyph can be dropped into a cell as is.
 * Curves are sampled with >= 8 segments per arc so they stay round at ~12 px tall.
 */

export const GLYPH_W = 0.7;
export const GLYPH_BASE = 0.8;

type Pt = [number, number];
type Strokes = Pt[][];

const r3 = (n: number): number => Math.round(n * 1000) / 1000;

/** Flat numbers → points: `p(.1, 0, .1, .8)` = [[.1, 0], [.1, .8]]. */
function p(...n: number[]): Pt[] {
  const out: Pt[] = [];
  for (let i = 0; i + 1 < n.length; i += 2) out.push([n[i], n[i + 1]]);
  return out;
}

/**
 * Elliptical arc around (cu, cv) with radii (ru, rv). Angles in degrees: 0 = right, 90 = down,
 * 180 = left, 270 / -90 = up (v points down). a1 < a0 walks the other way round.
 */
function arc(cu: number, cv: number, ru: number, rv: number, a0: number, a1: number): Pt[] {
  const n = Math.max(8, Math.ceil(Math.abs(a1 - a0) / 12));
  const out: Pt[] = [];
  for (let i = 0; i <= n; i++) {
    const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180;
    out.push([r3(cu + ru * Math.cos(a)), r3(cv + rv * Math.sin(a))]);
  }
  return out;
}

/** Joins point lists into one stroke, dropping consecutive duplicates. */
function S(...parts: Pt[][]): Pt[] {
  const out: Pt[] = [];
  for (const part of parts)
    for (const q of part) {
      const last = out[out.length - 1];
      if (!last || last[0] !== q[0] || last[1] !== q[1]) out.push(q);
    }
  return out;
}

/** 180° rotation inside the digit box (used for 9 = rotated 6). */
const rot = (strokes: Strokes): Strokes =>
  strokes.map((s) => s.map(([u, v]): Pt => [r3(GLYPH_W - u), r3(GLYPH_BASE - v)]));

